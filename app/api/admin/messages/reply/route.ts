import {NextRequest,NextResponse} from "next/server";
import {neon} from "@neondatabase/serverless";
import {getAdminSession} from "@/lib/admin-auth";

export const runtime="nodejs";
export const dynamic="force-dynamic";

async function guard(req:NextRequest){
  if(!(await getAdminSession()))return false;
  const origin=req.headers.get("origin"),host=req.headers.get("host");
  if(origin&&host){try{if(new URL(origin).host!==host)return false}catch{return false}}
  return true;
}
function db(){if(!process.env.LEGACY_DATABASE_URL)throw new Error("Database is not configured");return neon(process.env.LEGACY_DATABASE_URL)}
function escapeHtml(s:string){return s.replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]!))}
async function ensureTable(sql:any){
  await sql`CREATE TABLE IF NOT EXISTS cms_message_replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL REFERENCES cms_messages(id) ON DELETE CASCADE,
    admin_username VARCHAR(150) NOT NULL DEFAULT 'admin',
    body TEXT NOT NULL,
    provider_message_id TEXT,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`;
  await sql`CREATE INDEX IF NOT EXISTS cms_message_replies_message_idx ON cms_message_replies(message_id,sent_at DESC)`;
}
export async function GET(req:NextRequest){
  if(!(await guard(req)))return NextResponse.json({error:"Unauthorized"},{status:403});
  const messageId=Number(req.nextUrl.searchParams.get("messageId"));
  if(!Number.isSafeInteger(messageId)||messageId<1)return NextResponse.json({error:"Invalid message."},{status:400});
  try{
    const sql=db();await ensureTable(sql);
    const rows=await sql`SELECT id,body,sent_at FROM cms_message_replies WHERE message_id=${messageId} ORDER BY sent_at DESC,id DESC`;
    return NextResponse.json({ok:true,replies:rows});
  }catch(e){console.error("Message reply history failed",e);return NextResponse.json({error:"Could not load reply history."},{status:500})}
}
export async function POST(req:NextRequest){
  if(!(await guard(req)))return NextResponse.json({error:"Unauthorized"},{status:403});
  let b:any;try{b=await req.json()}catch{return NextResponse.json({error:"Invalid JSON."},{status:400})}
  const messageId=Number(b.messageId),body=typeof b.body==="string"?b.body.trim():"";
  if(!Number.isSafeInteger(messageId)||messageId<1||!body||body.length>5000)return NextResponse.json({error:"Enter a reply (up to 5,000 characters). "},{status:400});
  const apiKey=process.env.RESEND_API_KEY,from=process.env.CONTACT_FROM_EMAIL;
  if(!apiKey||!from)return NextResponse.json({error:"Email is not configured yet. Add RESEND_API_KEY and CONTACT_FROM_EMAIL to Preview environment variables."},{status:503});
  try{
    const sql=db();await ensureTable(sql);
    const found=await sql`SELECT id,name,email,service FROM cms_messages WHERE id=${messageId} LIMIT 1`;
    if(!found.length)return NextResponse.json({error:"Message not found."},{status:404});
    const msg=found[0] as any;
    const subject="Re: "+String(msg.service||"Your message").slice(0,150);
    const response=await fetch("https://api.resend.com/emails",{method:"POST",headers:{"Authorization":"Bearer "+apiKey,"Content-Type":"application/json"},body:JSON.stringify({from,to:[msg.email],subject,text:body,html:"<div style=\"font-family:Arial,sans-serif;line-height:1.7\">"+escapeHtml(body).replace(/\n/g,"<br>")+"</div>"})});
    const result:any=await response.json().catch(()=>({}));
    if(!response.ok){console.error("Email provider rejected reply",response.status,result);return NextResponse.json({error:"Email could not be sent. Check the sender address and email provider configuration."},{status:502})}
    const rows=await sql`INSERT INTO cms_message_replies(message_id,admin_username,body,provider_message_id) VALUES(${messageId},${(await getAdminSession())?.username||"admin"},${body},${String(result.id||"")}) RETURNING id,body,sent_at`;
    await sql`UPDATE cms_messages SET is_read=TRUE WHERE id=${messageId}`;
    return NextResponse.json({ok:true,reply:rows[0]});
  }catch(e){console.error("Message reply send failed",e);return NextResponse.json({error:"Reply could not be sent. Please try again."},{status:500})}
}
