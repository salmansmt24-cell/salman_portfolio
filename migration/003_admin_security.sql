-- Admin Security v1 (additive-only migration)
-- Target: LEGACY_DATABASE_URL on the Preview branch ONLY.
-- This migration creates new security tables and does not modify or delete any cms_* records.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS admin_security_profiles (
  username VARCHAR(100) PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL DEFAULT '',
  recovery_email VARCHAR(254),
  totp_secret_encrypted TEXT,
  totp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  recovery_codes_hashes TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS admin_security_profiles_recovery_email_uq
  ON admin_security_profiles (LOWER(recovery_email))
  WHERE recovery_email IS NOT NULL AND recovery_email <> '';

CREATE TABLE IF NOT EXISTS admin_security_sessions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  username VARCHAR(100) NOT NULL,
  session_token_hash CHAR(64) NOT NULL UNIQUE,
  device_label VARCHAR(240) NOT NULL DEFAULT 'Unknown device',
  user_agent TEXT NOT NULL DEFAULT '',
  ip_address INET,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS admin_security_sessions_user_active_idx
  ON admin_security_sessions (username, last_seen_at DESC)
  WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS admin_security_login_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL,
  event_type VARCHAR(40) NOT NULL CHECK (event_type IN ('login_success','login_failed','logout','password_changed','session_revoked','two_factor_enabled','two_factor_disabled','password_reset_requested','password_reset_completed')),
  user_agent TEXT NOT NULL DEFAULT '',
  ip_address INET,
  details_json JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_security_login_events_user_created_idx
  ON admin_security_login_events (username, created_at DESC);

CREATE TABLE IF NOT EXISTS admin_security_recovery_tokens (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  username VARCHAR(100) NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_security_recovery_tokens_user_idx
  ON admin_security_recovery_tokens (username, created_at DESC);

CREATE TABLE IF NOT EXISTS admin_security_audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL,
  action VARCHAR(100) NOT NULL,
  details_json JSONB NOT NULL DEFAULT '{}'::JSONB,
  ip_address INET,
  user_agent TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_security_audit_log_user_created_idx
  ON admin_security_audit_log (username, created_at DESC);
