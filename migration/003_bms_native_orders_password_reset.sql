-- BMS stays fully inside the website; no Google Sheets dependency.
CREATE TABLE IF NOT EXISTS bms_password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES bms_team_members(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  requested_ip INET,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_password_reset_member_idx
  ON bms_password_reset_tokens(member_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bms_password_reset_expiry_idx
  ON bms_password_reset_tokens(expires_at) WHERE used_at IS NULL;
ALTER TABLE bms_order_submissions DROP COLUMN IF EXISTS sheets_status;
ALTER TABLE bms_order_submissions DROP COLUMN IF EXISTS sheets_row_key;
