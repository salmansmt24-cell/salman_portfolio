-- BMS foundation: additive-only schema for team accounts, tasks, CRM and activity.
-- Safe to apply alongside the legacy cms_* schema. Does not alter or copy legacy records.
-- Apply only after reviewing on a non-production Neon branch.

CREATE TABLE IF NOT EXISTS bms_team_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255),
  role VARCHAR(40) NOT NULL DEFAULT 'Viewer'
    CHECK (role IN ('Super Admin','Admin','Team Leader','Sales Executive','Viewer')),
  status VARCHAR(20) NOT NULL DEFAULT 'invited'
    CHECK (status IN ('invited','pending','active','suspended','rejected')),
  invited_token_hash CHAR(64),
  invitation_expires_at TIMESTAMPTZ,
  created_by_username VARCHAR(100),
  approved_by_user_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  approved_at TIMESTAMPTZ,
  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS bms_team_members_email_lower_uq
  ON bms_team_members (LOWER(email));
CREATE UNIQUE INDEX IF NOT EXISTS bms_team_members_invited_token_uq
  ON bms_team_members (invited_token_hash) WHERE invited_token_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS bms_team_members_status_role_idx
  ON bms_team_members (status, role);

CREATE TABLE IF NOT EXISTS bms_user_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES bms_team_members(id) ON DELETE CASCADE,
  session_token_hash CHAR(64) NOT NULL UNIQUE,
  user_agent VARCHAR(1000) NOT NULL DEFAULT '',
  ip_address INET,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_user_sessions_member_idx
  ON bms_user_sessions (member_id, expires_at DESC);
CREATE INDEX IF NOT EXISTS bms_user_sessions_active_idx
  ON bms_user_sessions (expires_at) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS bms_tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(240) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'todo'
    CHECK (status IN ('todo','in_progress','review','blocked','completed','cancelled')),
  priority VARCHAR(16) NOT NULL DEFAULT 'normal'
    CHECK (priority IN ('low','normal','high','urgent')),
  assigned_to BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  created_by_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  created_by_legacy_username VARCHAR(100),
  due_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  related_entity_type VARCHAR(40),
  related_entity_id VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_tasks_assignee_status_idx
  ON bms_tasks (assigned_to, status, due_at);
CREATE INDEX IF NOT EXISTS bms_tasks_due_idx
  ON bms_tasks (due_at) WHERE status NOT IN ('completed','cancelled');
CREATE INDEX IF NOT EXISTS bms_tasks_created_idx
  ON bms_tasks (created_at DESC);

CREATE TABLE IF NOT EXISTS bms_task_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id BIGINT NOT NULL REFERENCES bms_tasks(id) ON DELETE CASCADE,
  author_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  author_legacy_username VARCHAR(100),
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_task_comments_task_idx
  ON bms_task_comments (task_id, created_at);

CREATE TABLE IF NOT EXISTS bms_leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contact_name VARCHAR(180) NOT NULL,
  company_name VARCHAR(180) NOT NULL DEFAULT '',
  email VARCHAR(255) NOT NULL DEFAULT '',
  phone VARCHAR(60) NOT NULL DEFAULT '',
  website VARCHAR(500) NOT NULL DEFAULT '',
  service_interest VARCHAR(160) NOT NULL DEFAULT '',
  source VARCHAR(80) NOT NULL DEFAULT 'manual',
  stage VARCHAR(24) NOT NULL DEFAULT 'new'
    CHECK (stage IN ('new','contacted','qualified','proposal_sent','negotiation','won','lost')),
  estimated_value NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (estimated_value >= 0),
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  owner_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  next_follow_up_at TIMESTAMPTZ,
  notes TEXT NOT NULL DEFAULT '',
  created_by_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  created_by_legacy_username VARCHAR(100),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_leads_stage_followup_idx
  ON bms_leads (stage, next_follow_up_at);
CREATE INDEX IF NOT EXISTS bms_leads_owner_idx
  ON bms_leads (owner_member_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS bms_leads_email_idx
  ON bms_leads (LOWER(email)) WHERE email <> '';

CREATE TABLE IF NOT EXISTS bms_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id BIGINT NOT NULL REFERENCES bms_team_members(id) ON DELETE CASCADE,
  notification_type VARCHAR(60) NOT NULL,
  title VARCHAR(200) NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  target_url VARCHAR(500) NOT NULL DEFAULT '',
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_notifications_member_unread_idx
  ON bms_notifications (member_id, created_at DESC) WHERE read_at IS NULL;

CREATE TABLE IF NOT EXISTS bms_activity_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
  actor_legacy_username VARCHAR(100),
  action VARCHAR(80) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id VARCHAR(100),
  summary TEXT NOT NULL DEFAULT '',
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_activity_entity_idx
  ON bms_activity_log (entity_type, entity_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bms_activity_actor_idx
  ON bms_activity_log (actor_member_id, created_at DESC);

-- Staff-submitted orders are kept separate until an admin reviews them.
-- Approved rows can be sent through a configured Sheets append integration.
CREATE TABLE IF NOT EXISTS bms_order_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submitted_by_member_id BIGINT NOT NULL REFERENCES bms_team_members(id) ON DELETE CASCADE,
  client_username VARCHAR(150) NOT NULL,
  project_title VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL DEFAULT 'General',
  amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
  fiverr_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fiverr_fee >= 0),
  order_url VARCHAR(500) NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  status VARCHAR(24) NOT NULL DEFAULT 'pending_review'
    CHECK (status IN ('pending_review','approved','rejected')),
  sheets_status VARCHAR(24) NOT NULL DEFAULT 'not_sent'
    CHECK (sheets_status IN ('not_sent','pending','synced','failed')),
  reviewed_by_username VARCHAR(100),
  reviewed_at TIMESTAMPTZ,
  review_note TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_order_submissions_status_idx
  ON bms_order_submissions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS bms_order_submissions_submitter_idx
  ON bms_order_submissions (submitted_by_member_id, created_at DESC);
