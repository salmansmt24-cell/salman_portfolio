-- BMS commercial operations: proposals and expense controls. Additive-only.
CREATE TABLE IF NOT EXISTS bms_proposals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 lead_id BIGINT REFERENCES bms_leads(id) ON DELETE SET NULL,
 title VARCHAR(240) NOT NULL,
 client_name VARCHAR(180) NOT NULL,
 description TEXT NOT NULL DEFAULT '',
 amount NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK(amount>=0),
 currency CHAR(3) NOT NULL DEFAULT 'USD',
 status VARCHAR(24) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','sent','accepted','declined','expired','cancelled')),
 valid_until DATE,
 owner_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
 created_by_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_proposals_owner_idx ON bms_proposals(owner_member_id,created_at DESC);
CREATE INDEX IF NOT EXISTS bms_proposals_status_idx ON bms_proposals(status,created_at DESC);
CREATE TABLE IF NOT EXISTS bms_expenses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(240) NOT NULL,
 category VARCHAR(100) NOT NULL DEFAULT 'General',
 description TEXT NOT NULL DEFAULT '',
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 currency CHAR(3) NOT NULL DEFAULT 'BDT',
 spent_on DATE NOT NULL DEFAULT CURRENT_DATE,
 receipt_url VARCHAR(1000) NOT NULL DEFAULT '',
 status VARCHAR(24) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected','reimbursed')),
 submitted_by_member_id BIGINT REFERENCES bms_team_members(id) ON DELETE SET NULL,
 reviewed_by_username VARCHAR(100),
 reviewed_at TIMESTAMPTZ,
 review_note TEXT NOT NULL DEFAULT '',
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS bms_expenses_status_idx ON bms_expenses(status,spent_on DESC);
CREATE INDEX IF NOT EXISTS bms_expenses_submitter_idx ON bms_expenses(submitted_by_member_id,created_at DESC);
